export interface BSDate {
  year: number
  month: number
  day: number
}

export interface ADDate {
  year: number
  month: number
  day: number
}

// BS start reference: BS 2000/1/1 = AD 1943/4/14
const BS_START_YEAR = 2000
const AD_START = { year: 1943, month: 4, day: 14 }

export function bsToAd(bs: BSDate): ADDate {
  const bsYear = bs.year
  const bsMonth = bs.month
  const bsDay = bs.day

  // Validate
  const yearData = BS_CALENDAR_DATA.find(d => d[0] === bsYear)
  if (!yearData) throw new Error(`BS year ${bsYear} not supported`)

  // Count total days from BS 2000/1/1
  let totalDays = 0
  for (let y = BS_START_YEAR; y < bsYear; y++) {
    const yd = BS_CALENDAR_DATA.find(d => d[0] === y)
    if (!yd) break
    for (let m = 1; m <= 12; m++) totalDays += yd[m]
  }
  for (let m = 1; m < bsMonth; m++) totalDays += yearData[m]
  totalDays += bsDay - 1

  // Add to AD start date
  const adStart = new Date(AD_START.year, AD_START.month - 1, AD_START.day)
  adStart.setDate(adStart.getDate() + totalDays)

  return {
    year: adStart.getFullYear(),
    month: adStart.getMonth() + 1,
    day: adStart.getDate(),
  }
}

export function adToBs(ad: ADDate): BSDate {
  const adDate = new Date(ad.year, ad.month - 1, ad.day)
  const adStart = new Date(AD_START.year, AD_START.month - 1, AD_START.day)

  let diffDays = Math.floor((adDate.getTime() - adStart.getTime()) / (1000 * 60 * 60 * 24))

  let bsYear = BS_START_YEAR
  let bsMonth = 1
  let bsDay = 1

  for (const yearData of BS_CALENDAR_DATA) {
    let yearDays = 0
    for (let m = 1; m <= 12; m++) yearDays += yearData[m]
    if (diffDays < yearDays) {
      bsYear = yearData[0]
      for (let m = 1; m <= 12; m++) {
        if (diffDays < yearData[m]) {
          bsMonth = m
          bsDay = diffDays + 1
          return { year: bsYear, month: bsMonth, day: bsDay }
        }
        diffDays -= yearData[m]
      }
    }
    diffDays -= yearDays
  }

  return { year: bsYear, month: bsMonth, day: bsDay }
}

